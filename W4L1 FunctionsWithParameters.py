def greet(name):
  print(f"Hello, {name}!")

# Call the function with a parameter
greet("Alice")
greet("Bob")

def add_numbers(a, b):
  return a + b

# Call the function with parameters
result1 = add_numbers (5, 10)
result2 = add_numbers (2.5, 4.5)

print(result1)
print(result2)
